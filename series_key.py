"""
Модуль определения ключа серии конференций.

Алгоритм полностью универсален — не содержит хардкода конкретных
аббревиатур или названий. Работает с любыми конференциями ИСАНД.

Правила определения ключа (по приоритету):

  A. «в рамках ... (АББР)» — берём аббревиатуру родительской конференции.
     Пример: «конф. (УРСС), проводимая в рамках МКПУ» → МКПУ

  B. Структура «РОДИТЕЛЬ (АББР_Р): ДОЧЕРНЯЯ» — берём АББР_Р.
     Пример: «Мультиконференция (МКПУ): конференция (УАКС)» → МКПУ

  C. Аббревиатура в скобках (первая по тексту, включая АББР-год).
     Пример: «Конф. (УБС, Воронеж)» → УБС
             «Конф. (ВСПУ-2023)» → ВСПУ

  D. Формат АББР-YYYY, АББР'YYYY, АББР YYYY в начале строки.
     Пример: «УБС-2023» → УБС, «MLSD'2019» → MLSD

  E. Нормализованное название в кавычках (без года, города, номера).
     Пример: «Инжиниринг предприятий...» (Москва) =
              «Инжиниринг предприятий...» (Российская) → одна серия

  F. Fallback: нормализованное полное название без служебных слов.

Функция get_series_key(conf_name) → (key_type, key)
  key_type: 'abbr' | 'title' | 'name'
  key: строка-ключ (нижний регистр для 'title'/'name', оригинал для 'abbr')
"""

import re

# ── Вспомогательные паттерны ──────────────────────────────────────────────────

# Аббревиатура: 2–8 заглавных букв (рус/лат), опциональный числовой суффикс (включая год -2023)
_ABBR_STRICT = re.compile(r'^([А-ЯЁA-Z]{2,8})(?:-\d{1,4})?$')

# Формат «АББР-YYYY», «АББР'YYYY», «АББР YYYY» в начале строки
_ABBR_YEAR_PREFIX = re.compile(r"^([А-ЯЁA-Z]{2,8})[-'\s](\d{4})")

# «в рамках ... (АББР)» или «в рамках ... АББР» — поиск родительской конференции
_VRAMKAKH = re.compile(
    r'в\s+рамках[^,\.]{0,100}'
    r'(?:'
    r'\(([А-ЯЁA-Z]{2,8})[,\s\)]'        # со скобками: (МКПУ)
    r'|(?<!\w)([А-ЯЁA-Z]{3,8})(?!\w)'   # без скобок: минимум 3 буквы, целое слово
    r')'
)

# Кавычки: «», "", ""
_QUOTED = re.compile(r'[«""]([^«""]{4,}?)[»""]')

# Служебные слова-префиксы (типы и масштабы конференций)
_SERVICE = re.compile(
    r'^('
    r'международн\w*\s+|всероссийск\w*\s+|российск\w*\s+|локальн\w*\s+|'
    r'межрегиональн\w*\s+|региональн\w*\s+|ежегодн\w*\s+|традиционн\w*\s+|'
    r'открыт\w*\s+|юбилейн\w*\s+|онлайн-\s*|научно-практическ\w*\s+|'
    r'научно-техническ\w*\s+|научно-методическ\w*\s+|практическ\w*\s+|'
    r'научн\w*\s+|с\s+международным\s+участием\s+|межвузовск\w*\s+|'
    r'межотраслевой\s+|межведомственн\w*\s+'
    r')*'
    r'('
    r'школа-конференция|школа-симпозиум|школа-семинар|конференция|симпозиум|'
    r'мультиконференция|совещание|семинар|форум|съезд|школа|чтения|сессия|'
    r'конгресс|workshop|конф\.\s*'
    r')\s*'
    r'('
    r'молодых\s+учёных\s+и\s+специалистов\s+|молодых\s+учёных\s+|'
    r'молодых\s+исследователей\s+|аспирантов\s+и\s+студентов\s+|'
    r'с\s+международным\s+участием\s+|'
    r'профессорско-преподавательского\s+состава\s+.*?\s+'
    r')*',
    re.IGNORECASE
)


# ── Вспомогательные функции ───────────────────────────────────────────────────

def _get_abbr(token: str):
    """Возвращает аббревиатуру из токена или None."""
    token = token.strip().rstrip('.')
    m = _ABBR_STRICT.match(token)
    return m.group(1) if m else None


def _find_parens_abbrs(text: str):
    """
    Ищет аббревиатуры во всех скобочных блоках текста по порядку.
    Учитывает формат «АББР-год» внутри скобок.
    """
    result = []
    for block in re.findall(r'\(([^)]+)\)', text):
        # Берём первый токен блока (до запятой или пробела)
        first = block.strip().split(',')[0].split()[0]
        a = _get_abbr(first)
        if a and len(a) >= 2:
            result.append(a)
    return result


def _find_vramkakh_abbr(text: str):
    """Ищет аббревиатуру родительской конференции в обороте «в рамках»."""
    m = _VRAMKAKH.search(text)
    if not m:
        return None
    # Группа 1 — в скобках, группа 2 — без скобок
    return m.group(1) or m.group(2)


def _normalize_quoted(text: str):
    """
    Извлекает содержимое кавычек и нормализует:
    убирает год, номер конференции, лишние пробелы.
    Возвращает нижний регистр или None.
    """
    m = _QUOTED.search(text)
    if not m:
        return None
    title = m.group(1).strip()
    # Убираем год в конце (через дефис или пробел)
    title = re.sub(r'[-–]?\s*\d{4}\s*$', '', title).strip()
    # Убираем порядковый номер в начале: «XVII», «10-я» и т.п.
    title = re.sub(r'^\s*[XLIVMCDIVX]+\s+|\s*\d+-[яйее]\s+', '', title).strip()
    title = re.sub(r'\s+', ' ', title).strip()
    return title.lower() if title and len(title) >= 4 else None


def _normalize_full(text: str) -> str:
    """
    Fallback-нормализация полного названия:
    убирает скобки с локацией/годом, год, порядковый номер, служебные слова.
    """
    s = text.strip()
    # Убираем скобочные блоки
    s = re.sub(r'\s*\([^)]*\)\s*', ' ', s)
    # Убираем год в конце
    s = re.sub(r"[-'–]\s*\d{4}\s*$", '', s).strip()
    s = re.sub(r'\s+\d{4}\s*$', '', s).strip()
    s = re.sub(r',\s*\d{4}\s*$', '', s).strip()
    # Убираем порядковый номер в начале
    s = re.sub(r'^\d+-[яйее]\s+|^[XLIVMCDIVX]+\s+', '', s, flags=re.IGNORECASE).strip()
    # Убираем служебные слова (несколько проходов)
    for _ in range(5):
        prev = s
        s = _SERVICE.sub('', s).strip()
        if s == prev:
            break
    s = re.sub(r'\s+', ' ', s).strip()
    return s.lower()[:80] if s else text.lower()[:50]


# ── Главная функция ───────────────────────────────────────────────────────────

def get_series_key(conf_name: str) -> tuple:
    """
    Определяет ключ серии для конференции.

    Параметры
    ----------
    conf_name : str
        Полное название конференции из поля conf_name API ИСАНД.

    Возвращает
    ----------
    (key_type, key) : tuple[str, str]
        key_type — 'abbr', 'title' или 'name'
        key      — строка-ключ (используется для группировки)
    """
    if not conf_name or not conf_name.strip():
        return ('name', '')

    name = conf_name.strip()

    # A. «в рамках ... (АББР)»
    vr = _find_vramkakh_abbr(name)
    if vr:
        return ('abbr', vr)

    # B. Структура «РОДИТЕЛЬ (АББР_Р): ДОЧЕРНЯЯ»
    if ':' in name:
        before = name.split(':', 1)[0]
        abbrs_before = _find_parens_abbrs(before)
        if abbrs_before:
            return ('abbr', abbrs_before[0])

    # C. Аббревиатура в скобках (первая по тексту)
    all_abbrs = _find_parens_abbrs(name)
    if all_abbrs:
        return ('abbr', all_abbrs[0])

    # D. Формат АББР-YYYY, АББР'YYYY, АББР YYYY в начале
    m_short = _ABBR_YEAR_PREFIX.match(name)
    if m_short:
        return ('abbr', m_short.group(1))

    # E. Нормализованное название в кавычках
    title = _normalize_quoted(name)
    if title:
        return ('title', title)

    # F. Fallback
    return ('name', _normalize_full(name))
